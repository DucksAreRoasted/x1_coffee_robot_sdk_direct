#!/usr/bin/env python3
"""用 Pinocchio+MuJoCo 离线检查 URDF 采样计划的腰部碰撞区。"""
import argparse, json
from pathlib import Path
import numpy as np
import pinocchio as pin
import mujoco


def model_xml():
    return '''<mujoco model="x1_waist_keepout">
      <option timestep="0.002"/>
      <worldbody>
        <body name="waist_keepout" pos="0 0 0.33857">
          <geom name="waist_plate_to_axis" type="box" size="0.1295 0.087 0.33857" contype="1" conaffinity="1"/>
        </body>
        <body name="tcp" pos="0 0 0">
          <freejoint/>
          <geom name="tcp_sphere" type="sphere" size="0.035" contype="1" conaffinity="1"/>
        </body>
      </worldbody>
    </mujoco>'''


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--urdf',type=Path,required=True)
    ap.add_argument('--plan',type=Path,required=True)
    ap.add_argument('--side',choices=['l','r'],default='r')
    ap.add_argument('--output',type=Path,required=True)
    a=ap.parse_args()
    robot=pin.buildModelFromUrdf(str(a.urdf)); data=robot.createData()
    frame=robot.getFrameId('right_gripper_tcp' if a.side=='r' else 'left_gripper_tcp')
    mj=mujoco.MjModel.from_xml_string(model_xml()); d=mujoco.MjData(mj)
    plan=json.loads(a.plan.read_text()); rows=[]
    for step in [{'pose_id':'seed','q':plan['seed']},*plan['steps']]:
        q=np.asarray(step['q'],float); pin.forwardKinematics(robot,data,q); pin.updateFramePlacements(robot,data)
        p=np.asarray(data.oMf[frame].translation); d.qpos[:3]=p; mujoco.mj_forward(mj,d)
        # sphere-vs-box contacts are generated by MuJoCo after forward.
        hit=any(d.contact[i].geom1==1 or d.contact[i].geom2==1 for i in range(d.ncon))
        rows.append(dict(pose_id=step['pose_id'], tcp_xyz=p.tolist(), collision=bool(hit)))
    out={'schema':'x1_mujoco_collision_preview_v1','side':a.side,'source_plan':str(a.plan),'rows':rows,
         'collision_count':sum(r['collision'] for r in rows),'deployment_allowed':False}
    a.output.write_text(json.dumps(out,ensure_ascii=False,indent=2))
    print(json.dumps({'collision_count':out['collision_count'],'total':len(rows),'output':str(a.output)},ensure_ascii=False))


if __name__=='__main__': main()
